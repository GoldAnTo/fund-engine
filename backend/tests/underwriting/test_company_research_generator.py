def test_input_receipts_for_interleaved_requests_do_not_share_mutable_state():
    module = _module()
    client = ExplicitTestClient()
    generator = module.CompanyResearchDraftGenerator(client)
    assert hasattr(generator, "input_hash_for"), (
        "failed calls need a pure input receipt"
    )
    first = _input()
    second = deepcopy(first)
    second["user_focus"] = "广告业务的竞争壁垒"
    original = deepcopy(first)
    a = generator.input_hash_for(**first)
    b = generator.input_hash_for(**second)
    assert a != b
    assert generator.generate(**first).input_hash == a
    assert generator.input_hash_for(**second) == b
    assert first == original
    assert len(client.calls) == 1


