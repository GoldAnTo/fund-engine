def test_numeric_values_are_allowed_in_exact_source_quotes():
    inputs = _input()
    exact_quote = "Reported Cloud revenue was 58700 million dollars."
    inputs["source_bundle"]["excerpts"][0]["text"] += "\n" + exact_quote
    _rehash_bundle(inputs["source_bundle"])
    response = _response()
