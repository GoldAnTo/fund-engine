class ExplicitTestClient:
    model_version = "explicit-test-client"

    def __init__(self, response=None):
        self.response = _response() if response is None else response
        self.calls = []

    def chat_json(self, messages, schema_hint=""):
        self.calls.append((deepcopy(messages), schema_hint))
        if isinstance(self.response, Exception):
            raise self.response
        return deepcopy(self.response)


def _generate(*, response=None, inputs=None):
    module = _module()
    client = ExplicitTestClient(response)
    result = module.CompanyResearchDraftGenerator(client).generate(
        **(inputs or _input())
    )
    return module, client, result


def _rehash_bundle(bundle):
    bundle["excerpts_hash"] = canonical_hash(bundle["excerpts"])
    bundle["bundle_hash"] = canonical_hash(
        {key: value for key, value in bundle.items() if key != "bundle_hash"}
    )


def test_grounded_draft_contains_real_excerpt_focus_and_resolved_citations():
    module, client, generated = _generate()
    messages, hint = client.calls[0]
    prompt = json.loads(messages[1]["content"])
    assert hint == "company_research_draft"
    assert prompt["user_focus"] == _input()["user_focus"]
    assert (
        prompt["excerpts"][0]["text"]
        == _input()["source_bundle"]["excerpts"][0]["text"]
    )
    assert prompt["facts"][0]["value"] == "58700"
    assert generated.prompt_version == module.PROMPT_VERSION
    assert generated.model_version == client.model_version
    assert generated.payload["candidate_status"] == "machine_draft"
    citation = generated.payload["business_analysis"][0]["citations"][0]
    assert citation == {
        "excerpt_id": "annual-cloud",
        "quote": QUOTE,
        "source_id": "annual",
        "raw_hash": "a" * 64,
        "source_url": "https://issuer.test/annual.pdf",
        "locator": "Cloud results",
    }
    assert (
        generated.payload["source_bundle_hash"]
        == _input()["source_bundle"]["bundle_hash"]
    )
    assert generated.output_hash == canonical_hash(
        {"payload": generated.payload, "markdown": generated.markdown}
    )
    assert "客户使用基础设施服务" in generated.markdown
    assert "58700 USD\\_million" in generated.markdown
    assert "2026-08-25" in generated.markdown
    assert "未经人工确认" in generated.markdown
    assert "候选假设" in generated.markdown
    assert "反证" in generated.markdown
    assert "[来源" in generated.markdown
    assert "https://issuer.test/annual.pdf" in generated.markdown
    assert "正式估值" in generated.markdown


def test_focus_is_bound_into_prompt_and_input_hash_not_only_report_heading():
    first = _input()
